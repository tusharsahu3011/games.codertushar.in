export function getLocationsByCategory(category: string): SpyfallLocation[] {
  if (category === 'all') return SPYFALL_LOCATIONS;
  return SPYFALL_LOCATIONS.filter((l) => l.category === category);
}

export function getRandomLocation(category: string = 'all'): SpyfallLocation {
  const filtered = getLocationsByCategory(category);
  const pool = filtered.length > 0 ? filtered : SPYFALL_LOCATIONS;
  const index = Math.floor(Math.random() * pool.length);
  return pool[index];
}
